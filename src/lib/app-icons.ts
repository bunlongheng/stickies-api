// Last-resort sub-icon so a note is NEVER rendered without a source badge.
// Used when neither the posting app nor the device resolves to an icon (e.g. a
// note created directly in the browser, or an unknown attribution key).
export const DEFAULT_APP_ICON = "/app-icons/stickies.png";

// Resolve the icon path for an attribution key, or null if none exists (caller
// falls back to a text chip). Tries an exact id match first, then the leading
// segment so suffixed keys like "automations-pipeline" map to "automations".
export function appIconForKey(key: string | null | undefined): string | null {
    if (!key) return null;
    const k = key.toLowerCase();
    const file = APP_ICON_FILES[k] ?? APP_ICON_FILES[k.split("-")[0] ?? k];
    return file ? `/app-icons/${file}` : null;
}
